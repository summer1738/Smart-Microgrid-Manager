"""Pydantic schemas for API request/response."""
from datetime import datetime
from typing import Any, List, Optional

from pydantic import BaseModel, Field


class TempHumiditySnapshot(BaseModel):
    present: bool = False
    freshness: str = "missing"
    age_seconds: Optional[int] = None
    timestamp: Optional[datetime] = None
    temp_c: Optional[float] = None
    humidity_percent: Optional[float] = None


class LightSnapshot(BaseModel):
    present: bool = False
    freshness: str = "missing"
    age_seconds: Optional[int] = None
    timestamp: Optional[datetime] = None
    is_sunny: Optional[bool] = None


class ApplianceCreate(BaseModel):
    # external_id is optional and normally autogenerated by the backend.
    external_id: Optional[str] = Field(None, min_length=1, max_length=64)
    name: str = Field(..., min_length=1, max_length=255)
    priority: int = Field(1, ge=1, le=3)
    rated_watts: float = Field(..., gt=0)
    usage_mode: str = Field("scheduled", pattern="^(scheduled|on_demand)$")
    default_run_minutes: int = Field(30, ge=5, le=240)
    schedule_prefs: Optional[str] = None
    relay_topic: Optional[str] = None


class ApplianceUpdate(BaseModel):
    name: Optional[str] = Field(None, min_length=1, max_length=255)
    priority: Optional[int] = Field(None, ge=1, le=3)
    rated_watts: Optional[float] = Field(None, gt=0)
    usage_mode: Optional[str] = Field(None, pattern="^(scheduled|on_demand)$")
    default_run_minutes: Optional[int] = Field(None, ge=5, le=240)
    schedule_prefs: Optional[str] = None
    relay_topic: Optional[str] = None
    is_on: Optional[bool] = None


class ApplianceManualControlRequest(BaseModel):
    is_on: bool


class ApplianceOut(BaseModel):
    id: int
    external_id: str
    name: str
    priority: int
    rated_watts: float
    usage_mode: str = "scheduled"
    default_run_minutes: int = 30
    schedule_prefs: Optional[str] = None
    relay_topic: Optional[str] = None
    is_on: bool
    manual_override_active: bool = False

    class Config:
        from_attributes = True


class UserOut(BaseModel):
    id: int
    name: str
    username: str
    role: str

    class Config:
        from_attributes = True


class LoginRequest(BaseModel):
    username: str = Field(..., min_length=1, max_length=64)
    password: str = Field(..., min_length=1, max_length=255)


class RegisterRequest(BaseModel):
    name: str = Field(..., min_length=2, max_length=255)
    username: str = Field(..., min_length=3, max_length=64, pattern=r"^[A-Za-z0-9._-]+$")
    password: str = Field(..., min_length=8, max_length=255)


class AuthSessionOut(BaseModel):
    user: UserOut
    expires_at: datetime


class PvSnapshot(BaseModel):
    power_kw: float
    voltage: float
    current_a: float
    timestamp: datetime


class BatterySnapshot(BaseModel):
    soc_percent: float
    voltage: float
    current_a: float
    timestamp: datetime


class LoadSnapshot(BaseModel):
    appliance_id: str
    name: str
    power_kw: float
    state: str
    unexpected_override: bool = False


class StatusOut(BaseModel):
    timestamp: datetime
    pv: PvSnapshot
    battery: BatterySnapshot
    loads: List[LoadSnapshot]
    total_load_kw: float
    available_export_kw: float = 0.0
    battery_is_charging: bool = False
    battery_status_label: str = "Unknown"
    battery_status_level: str = "neutral"
    manual_override_detected: bool = False
    manual_override_messages: List[str] = []
    simulated: bool = True


class ForecastSeries(BaseModel):
    """Placeholder for LSTM forecast output."""
    timestamps: List[str]
    generation_kw: List[float]
    consumption_kw: List[float]


class ForecastOut(BaseModel):
    generated_at: datetime
    horizon_hours: int
    series: Optional[ForecastSeries] = None
    message: Optional[str] = None


class ScheduleSlotOut(BaseModel):
    appliance_id: int
    appliance_name: str
    start_ts: datetime
    end_ts: datetime
    planned_state: str
    status: str


class ScheduleOut(BaseModel):
    generated_at: Optional[datetime] = None
    slots: List[ScheduleSlotOut] = []
    message: Optional[str] = "IEBA schedule not yet implemented."


class ApplianceRunRequest(BaseModel):
    duration_minutes: int = Field(30, ge=5, le=240)


class ApplianceRunDecisionOut(BaseModel):
    ok: bool
    appliance_id: int
    appliance_name: str
    decision: str
    message: str
    duration_minutes: int
    recommended_start_ts: Optional[datetime] = None
    scheduled_start_ts: Optional[datetime] = None
    scheduled_end_ts: Optional[datetime] = None


class HistoryPoint(BaseModel):
    timestamp: datetime
    power_kw: Optional[float] = None
    soc_percent: Optional[float] = None
    total_load_kw: Optional[float] = None
    available_export_kw: Optional[float] = None


class StatusHistoryOut(BaseModel):
    """Time-series of PV, battery SOC, and total load for charts and LSTM export."""
    points: List[HistoryPoint]
    hours: int


class SensorSnapshotOut(BaseModel):
    present: bool = False
    freshness: str = "missing"
    age_seconds: Optional[int] = None
    timestamp: Optional[datetime] = None
    power_kw: Optional[float] = None
    voltage: Optional[float] = None
    current_a: Optional[float] = None
    soc_percent: Optional[float] = None


class LoadSensorSnapshotOut(BaseModel):
    appliance_id: str
    name: str
    present: bool = False
    freshness: str = "missing"
    age_seconds: Optional[int] = None
    timestamp: Optional[datetime] = None
    power_kw: float = 0.0
    state: str = "missing"
    expected_on: bool = False
    manual_override_active: bool = False


class SensorMonitorOut(BaseModel):
    generated_at: datetime
    mode: str
    freshness_threshold_seconds: int
    pv: SensorSnapshotOut
    battery: SensorSnapshotOut
    temp_humidity: TempHumiditySnapshot = TempHumiditySnapshot()
    light: LightSnapshot = LightSnapshot()
    loads: List[LoadSensorSnapshotOut]
    mqtt: dict[str, Any] = Field(default_factory=dict)


class ModelCheckpointInfo(BaseModel):
    path: str
    seq_len: int
    feat_dim: int
    hidden: int
    feature_names: List[str]
    validation_smape: Optional[float] = None
    validation_mape_masked: Optional[float] = None
    validation_mae: Optional[float] = None
    validation_mape_legacy: Optional[float] = None


class InsightEvidence(BaseModel):
    label: str
    value: str


class DescriptiveInsight(BaseModel):
    category: str
    severity: str = Field(..., pattern="^(info|success|warning|critical)$")
    title: str
    message: str
    recommendation: Optional[str] = None
    evidence: List[InsightEvidence] = Field(default_factory=list)


class ForecastInsightsOut(BaseModel):
    generated_at: datetime
    forecast_horizon_hours: int
    battery_reserve_target_percent: Optional[float] = None
    summary: str
    insights: List[DescriptiveInsight] = Field(default_factory=list)


class ModelMonitorOut(BaseModel):
    """LSTM forecast pipeline status for the Model Monitor UI."""
    torch_available: bool
    gen_path: str
    load_path: str
    gen_file_exists: bool
    load_file_exists: bool
    models_load_ok: bool
    gen: Optional[ModelCheckpointInfo] = None
    load: Optional[ModelCheckpointInfo] = None
    errors: List[str] = []
    seed_source: str = "synthetic"
    ieba_uses_simulated_forecast: bool = True
    lstm_forecast_active: bool = False
    forecast_message: str = ""
    inference_ms: Optional[float] = None
    model_series: Optional[ForecastSeries] = None
    simulated_series: Optional[ForecastSeries] = None
    # Validation metrics from training (when checkpoint includes them)
    # Live metrics: model vs actual from DB history (when LSTM active and history available)
    live_smape_gen: Optional[float] = None
    live_smape_load: Optional[float] = None
    live_mape_masked_gen: Optional[float] = None
    live_mape_masked_load: Optional[float] = None
    live_mae_gen: Optional[float] = None
    live_mae_load: Optional[float] = None
    live_metrics_hours: Optional[int] = None
    descriptive_summary: Optional[str] = None
    descriptive_insights: List[DescriptiveInsight] = Field(default_factory=list)
